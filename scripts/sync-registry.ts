import { readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

/**
 * Regenerates src/server/data/registry.ts from the question files on disk.
 * Run after adding or removing question files so the bundled bank stays in sync.
 */

const ROOT = path.resolve("src/server/data/questions");
const OUT = path.resolve("src/server/data/registry.ts");

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (entry.endsWith(".json")) out.push(full);
  }
  return out;
}

const files = walk(ROOT).sort();
if (files.length === 0) {
  throw new Error("No question files found");
}

function identFor(file: string): string {
  const rel = path.relative(ROOT, file).replace(/\.json$/, "");
  return "file_" + rel.replace(/[^a-zA-Z0-9]/g, "_");
}

const lines: string[] = [];
for (const file of files) {
  const rel = "./" + path.relative(path.dirname(OUT), file).split(path.sep).join("/");
  lines.push(`import ${identFor(file)} from "${rel}";`);
}
lines.push('import type { TopicFile } from "../../shared/question";');
lines.push("");
lines.push("/** Generated by scripts/sync-registry.ts. Do not edit by hand. */");
lines.push("export const TOPIC_FILES = [");
for (const file of files) {
  lines.push(`  ${identFor(file)},`);
}
lines.push("] as unknown as TopicFile[];");
lines.push("");

writeFileSync(OUT, lines.join("\n"));
console.log(`registry.ts regenerated with ${files.length} files`);
